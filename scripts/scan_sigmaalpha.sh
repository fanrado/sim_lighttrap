#!/usr/bin/env bash
#
# scan_sigmaalpha.sh — sweep the pTP coating surface roughness (pTPsigmaAlpha,
# the facet-slope RMS in radians) and print the efficiency chain for each value,
# so the effect of pTP surface roughness on light collection can be compared.
#
# sigmaAlpha = 0 is a perfectly smooth pTP film, which TIR-traps a large fraction
# of the WLS photons inside the 2 um layer; raising it scatters those guided
# modes out toward the blue WLS slab / SiPMs.
#
# Source/run is driven by mac/run_285.mac (285 nm-style spectrum, 1000 events).
# For each value it:
#   1. writes a temp macro that sets /detector/pTPsigmaAlpha, reinitialises the
#      geometry, then executes run_285.mac,
#   2. runs ./sim_lighttrap on it (output -> build/output_apexltsim0.root),
#   3. renames the output to build/out_sigma_<label>.root,
#   4. runs analysis/analyze_efficiency.py on it.
#
# Usage:
#   scripts/scan_sigmaalpha.sh [sigma ...]
#
#   sigma ...  optional; list of sigmaAlpha values in radians
#              (default: 0.0 0.05 0.1 0.2 0.3).  0.1 rad ~ 6 deg.
#
# Examples:
#   scripts/scan_sigmaalpha.sh                  # default sweep
#   scripts/scan_sigmaalpha.sh 0.0 0.1 0.2      # just these three
#
# Event count comes from run_285.mac (/run/beamOn 1000); edit that macro to
# change it.  Requires a built build/sim_lighttrap and python3.13.

set -euo pipefail

# Resolve repo root from this script's location, so it runs from anywhere.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$SCRIPT_DIR/.." && pwd)"
BUILD="$REPO/build"
BIN="$BUILD/sim_lighttrap"
RUN_MAC="run_285.mac"                  # build-dir copy; pulls in spectrum_macro.mac
ANALYZER="$REPO/analysis/analyze_efficiency.py"
PYTHON="${PYTHON:-python3.13}"

# ── Arguments ────────────────────────────────────────────────────────────────
SIGMAS=("$@")
[ ${#SIGMAS[@]} -eq 0 ] && SIGMAS=(0.0 0.05 0.1 0.2 0.3)

# ── Sanity checks ────────────────────────────────────────────────────────────
[ -x "$BIN" ]                || { echo "error: $BIN not found or not executable — build it first." >&2; exit 1; }
[ -f "$BUILD/$RUN_MAC" ]     || { echo "error: $BUILD/$RUN_MAC not found (run cmake to copy macros)." >&2; exit 1; }

echo "Repo:     $REPO"
echo "Binary:   $BIN"
echo "Source:   $RUN_MAC"
echo "sigmas:   ${SIGMAS[*]} (rad)"
echo

# ── Run each sigmaAlpha ──────────────────────────────────────────────────────
for sigma in "${SIGMAS[@]}"; do
  # Reject anything that is not a non-negative number.
  case "$sigma" in
    ''|*[!0-9.]*) echo "error: invalid sigmaAlpha '$sigma' (want a number in radians)" >&2; exit 1 ;;
  esac
  label="${sigma//./p}"                # 0.1 -> 0p1 for a clean filename
  mac="$BUILD/sigma_${label}.mac"

  cat > "$mac" <<EOF
# Auto-generated by scan_sigmaalpha.sh — pTP roughness sweep point.
/detector/pTPsigmaAlpha $sigma
/run/reinitializeGeometry
/control/execute $RUN_MAC
EOF

  echo "===== running pTPsigmaAlpha = $sigma rad ====="
  # Run from build/ so run_285.mac and its spectrum_macro.mac resolve, and the
  # output file lands there.
  ( cd "$BUILD" && "$BIN" "sigma_${label}.mac" >/dev/null )
  mv "$BUILD/output_apexltsim0.root" "$BUILD/out_sigma_${label}.root"
  echo "  -> build/out_sigma_${label}.root"
  echo
done

# ── Compare ──────────────────────────────────────────────────────────────────
for sigma in "${SIGMAS[@]}"; do
  label="${sigma//./p}"
  echo "===== efficiency: pTPsigmaAlpha = $sigma rad ====="
  "$PYTHON" "$ANALYZER" "$BUILD/out_sigma_${label}.root"
  echo
done
