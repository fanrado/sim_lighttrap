MyRunAction::MyRunAction()
{
  G4AnalysisManager *man = G4AnalysisManager::Instance();

  // ── Ntuple ID → detector-region map (first layer + PMT readout) ─────────────
  //   0  Energy              — deposited energy per event (optical runs: 0)
  //   1  Primary             — (a) primary particle info (beam photon)
  //   2  WLSPhoton           — WLS/scintillation photon births (pTP emission)
  //   3  OpticalValidation   — Fresnel/reflection validation of the primaries
  //   4  FirstLayerBackplane — (b) photons crossing the first-layer back (+z) face
  //   5  FirstLayerEdges     — (c) photons reaching the first-layer ±x edges
  //   6  PMTPhotons          — every photon reaching the PMT photocathode (pre-QE)
  //   7  PMTHits             — detected photo-electrons (post-QE)
  // Ntuples 4/5 share MyLeakDetector's fill and carry a 'forward' int column
  // (index 7): 1 if mom.z()>0 (forward, out of layer 1), else 0 (back-reflected).
  // Ntuples 6/7 share MyPMTDetector's fill and carry a 'primary' int column:
  // 1 = unshifted beam photon, 0 = pTP-shifted WLS daughter.

  man->CreateNtuple("Energy", "Energy");
  man->CreateNtupleDColumn("fEdep");
  man->FinishNtuple(0);

  // Primary particle information:
  man->CreateNtuple("Primary", "Primary Particle Information");
  man->CreateNtupleIColumn("eventID");
  man->CreateNtupleDColumn("posX"); // position
  man->CreateNtupleDColumn("posY");
  man->CreateNtupleDColumn("posZ");
  man->CreateNtupleDColumn("momX"); // momentum
  man->CreateNtupleDColumn("momY");
  man->CreateNtupleDColumn("momZ");
  man->CreateNtupleDColumn("wl"); // wavelength
  man->CreateNtupleIColumn("pdg"); // pdg code
  man->FinishNtuple(1);

  // optical photons generated by WLS process
  man->CreateNtuple("WLSPhoton", "Optical Photons from WLS");
  man->CreateNtupleIColumn("eventID");        // Event identifier
  man->CreateNtupleDColumn("posX");           // Emission position X
  man->CreateNtupleDColumn("posY");           // Emission position Y
  man->CreateNtupleDColumn("posZ");           // Emission position Z
  man->CreateNtupleDColumn("cosTheta");       // zenith angle
  man->CreateNtupleDColumn("phi");            // azimuth angle
  man->CreateNtupleIColumn("processName");    // WLS or Scintillation
  man->CreateNtupleDColumn("t");              // Global time of emission
  man->CreateNtupleIColumn("pdg");            // PDG code of the photon
  man->CreateNtupleDColumn("wl");             // wavelength
  man->CreateNtupleIColumn("matName");        // material name (NameMap code)
  man->FinishNtuple(2);

  // Primary photon properties for optical validation (Fresnel, reflection)
  man->CreateNtuple("OpticalValidation", "Optical Properties Validation");
  man->CreateNtupleIColumn("eventID");
  man->CreateNtupleDColumn("wavelength");
  man->CreateNtupleDColumn("incidentAngle");
  man->CreateNtupleSColumn("material");
  man->CreateNtupleIColumn("reflected");  // 1 if reflected (finalZ < source plane), 0 if transmitted
  man->CreateNtupleDColumn("posX");
  man->CreateNtupleDColumn("posY");
  man->CreateNtupleDColumn("posZ");
  man->FinishNtuple(3);

  // (b) FirstLayerBackplane: photons crossing the back (+z) face of the first
  // layer (pTP/UV-acrylic stack) into the LAr gap.  Pass-through counter — the
  // photon continues to the PMT — so only photons that escape first-layer TIR
  // are counted.  Pairs with WLSPhoton (birth) for first-layer collection.
  man->CreateNtuple("FirstLayerBackplane", "Photons crossing the first-layer back face");
  man->CreateNtupleIColumn("eventID");
  man->CreateNtupleDColumn("fX");
  man->CreateNtupleDColumn("fY");
  man->CreateNtupleDColumn("fZ");
  man->CreateNtupleDColumn("fT");
  man->CreateNtupleDColumn("fwl");
  man->CreateNtupleDColumn("fcosTheta");   // >0 = forward into gap toward the PMT
  man->CreateNtupleIColumn("forward");     // 1 if mom.z()>0 (forward), else 0
  man->FinishNtuple(4);

  // (c) FirstLayerEdges: photons reaching the ±x edges of the first layer.
  // Pass-through counter — records lateral escape from the first-layer stack.
  man->CreateNtuple("FirstLayerEdges", "Photons reaching the first-layer +/-x edges");
  man->CreateNtupleIColumn("eventID");
  man->CreateNtupleDColumn("fX");
  man->CreateNtupleDColumn("fY");
  man->CreateNtupleDColumn("fZ");
  man->CreateNtupleDColumn("fT");
  man->CreateNtupleDColumn("fwl");
  man->CreateNtupleDColumn("fcosTheta");   // momentum-z direction cosine
  man->CreateNtupleIColumn("forward");     // 1 if mom.z()>0 (forward), else 0
  man->FinishNtuple(5);

  // PMT readout: the photocathode is a terminal counter.  'primary' = 1 if the
  // photon is the unshifted beam photon itself (parentID 0), 0 if it is a WLS
  // daughter (pTP-shifted light).  cosTheta = momentum-z cosine at the
  // photocathode (+1 = normal incidence from the first layer).
  man->CreateNtuple("PMTPhotons", "Photons reaching the PMT photocathode (pre-QE)");
  man->CreateNtupleIColumn("eventID");
  man->CreateNtupleDColumn("fX");
  man->CreateNtupleDColumn("fY");
  man->CreateNtupleDColumn("fZ");
  man->CreateNtupleDColumn("fT");
  man->CreateNtupleDColumn("fwl");
  man->CreateNtupleDColumn("fcosTheta");
  man->CreateNtupleIColumn("primary");
  man->FinishNtuple(6);

  man->CreateNtuple("PMTHits", "Photo-electrons detected by the PMT (post-QE)");
  man->CreateNtupleIColumn("eventID");
  man->CreateNtupleDColumn("fX");
  man->CreateNtupleDColumn("fY");
  man->CreateNtupleDColumn("fZ");
  man->CreateNtupleDColumn("fT");
  man->CreateNtupleDColumn("fwl");
  man->CreateNtupleDColumn("fcosTheta");
  man->CreateNtupleIColumn("primary");
  man->FinishNtuple(7);
}

MyRunAction::~MyRunAction()
{}

void MyRunAction::BeginOfRunAction(const G4Run* run)
{
  G4AnalysisManager *man = G4AnalysisManager::Instance();

  G4int runNumber = run->GetRunID();
  std::stringstream strRunID;
  strRunID << runNumber;
  man->OpenFile("output_apexltsim"+strRunID.str()+".root");

  RunCounters::Instance().Reset();
}

void MyRunAction::EndOfRunAction(const G4Run* run)
{
  G4AnalysisManager *man = G4AnalysisManager::Instance();

  man->Write();
  man->CloseFile();

  // ── Viewer-independent run summary ──────────────────────────────────────────
  // Printed to G4cout (terminal / Qt "Output" pane) after every /run/beamOn so
  // the physics of the run can be checked without the ROOT file or the viewer.
  RunCounters& c = RunCounters::Instance();
  c.nPrimary = run->GetNumberOfEvent();
  const auto* det = dynamic_cast<const MyLightTrapConstruction*>(
      G4RunManager::GetRunManager()->GetUserDetectorConstruction());
  auto pct = [&](G4long k) -> G4String {
    if (c.nPrimary == 0) return "   n/a";
    std::ostringstream os; os << std::fixed << std::setprecision(1) << std::setw(5)
                              << 100.0 * k / c.nPrimary << " %";
    return os.str();
  };
  G4cout << "\n============ sim_lighttrap run " << run->GetRunID() << " summary ============\n";
  if (det)
    G4cout << "  sample (pTP on acrylic) : " << (det->WithSample() ? "IN the beam (with_sample=on)" : "ABSENT (with_sample=off, reference run)") << "\n"
           << "  world medium            : " << det->WorldMedium()
           << "   gap " << det->GapThickness()/mm << " mm, PMT faceplate " << det->WindowThickness()/mm
           << " mm, photocathode Ø " << det->PMTDiameter()/mm << " mm\n";
  G4cout << "  beam photons            : " << std::setw(8) << c.nPrimary << "\n"
         << "  WLS photons born in pTP : " << std::setw(8) << c.nWLSpTP      << "  (" << pct(c.nWLSpTP) << " of beam)";
  if (c.nWLSother) G4cout << "   [+" << c.nWLSother << " born elsewhere]";
  G4cout << "\n"
         << "  leaving layer 1 -> PMT  : " << std::setw(8) << c.nLayer1Forward << "  (" << pct(c.nLayer1Forward) << ")\n"
         << "  reaching layer-1 edges  : " << std::setw(8) << c.nLayer1Edges   << "\n"
         << "  photons on photocathode : " << std::setw(8) << c.nPMTPhotons    << "  (" << pct(c.nPMTPhotons) << ")  unshifted beam: "
         << c.nPMTDirect << ", pTP-shifted: " << (c.nPMTPhotons - c.nPMTDirect) << "\n"
         << "  PMT hits (after QE)     : " << std::setw(8) << c.nPMTHits       << "  (" << pct(c.nPMTHits) << " of beam)\n";
  if (det && det->WithSample() && c.nPrimary > 0 && c.nWLSpTP == 0)
    G4cout << "  !! sample present but NO wavelength shifting occurred - check the beam energy "
              "(pTP absorbs < ~320 nm) and the materials !!\n";
  G4cout << "=====================================================\n" << G4endl;
}
